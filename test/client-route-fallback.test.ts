describe('the supported and refused combinations', () => {
  it('React + Vite + React Router + client-route-fallback is supported', () => {
    expect(() => resolveProject(react(), adapters)).not.toThrow();
  });

  it('React + Vite + React Router + not-found is refused', () => {
    const text = refusalText(react({ features: ['starter:full', 'not-found'] }));
    expect(text).toContain('file-based-routing');
    expect(text).toContain('Not-found page');
  });

  it('React + Vite + React Router + not-found + client-route-fallback is refused', () => {
    // The combination somebody will eventually ask for, reasoning that the
    // fallback "covers" the not-found requirement. It does not: one is a
    // response and the other is a render, and selecting a second feature never
    // satisfies the first one's capability.
    const text = refusalText(
      react({ features: ['starter:full', 'not-found', 'client-route-fallback'] }),
    );
    expect(text).toContain('file-based-routing');
  });

  it('the refusal of that pair names not-found, not the fallback', () => {
    const text = refusalText(
      react({ features: ['starter:full', 'not-found', 'client-route-fallback'] }),
    );
    // The refusal has to be about the requirement that is unmet, not about the
    // pair being selected together. Selecting the fallback is fine; what fails
    // is that nothing here provides file-based routing, and the report says so
    // while listing client-side-routing among what the stack *does* provide.
    expect(text).toContain('Not-found page requires file-based-routing');
    expect(text).not.toContain('Client-side route fallback requires');
    expect(text).toMatch(/provides:[^\n]*client-side-routing/);
  });

  it('React + Vite without a router is refused, naming the routing capability', () => {
    // React provides `spa-routing` on its own. That is navigation without a
    // reload, not a route table - so there is nothing for an unmatched address
    // to fail to match, and the view would be a component nothing renders.
    const text = refusalText(react({ router: 'none' as RouterId }));
    expect(text).toContain('client-side-routing');
    expect(text).toContain('Client-side route fallback');
    expect(REACT_DECLARATION.provides).toContain('spa-routing');
    expect(REACT_DECLARATION.provides).not.toContain('client-side-routing');
  });

  it('Astro + not-found is supported and Astro + the fallback is not', () => {
    // The mirror image, and the reason neither feature subsumes the other.
    expect(() => resolveProject(astro(['starter:full', 'not-found']), adapters)).not.toThrow();
    expect(refusalText(astro(['starter:full', 'client-route-fallback']))).toContain(
      'client-side-routing',
    );
    expect(ASTRO_DECLARATION.provides).toContain('file-based-routing');
    expect(ASTRO_DECLARATION.provides).not.toContain('client-side-routing');
  });

  it('the three-way distinction holds across all four feature selections', () => {
    const cases: readonly { features: FeatureId[]; astroOk: boolean; reactOk: boolean }[] = [
      { features: ['starter:full'], astroOk: true, reactOk: true },
      { features: ['starter:full', 'not-found'], astroOk: true, reactOk: false },
      { features: ['starter:full', 'client-route-fallback'], astroOk: false, reactOk: true },
      {
        features: ['starter:full', 'not-found', 'client-route-fallback'],
        astroOk: false,
        reactOk: false,
      },
    ];

    for (const entry of cases) {
      const label = entry.features.join(' + ');
      expect(
        (() => {
          try {
            resolveProject(astro(entry.features), adapters);
            return true;
          } catch {
            return false;
          }
        })(),
        `astro + ${label}`,
      ).toBe(entry.astroOk);
      expect(
        (() => {
          try {
            resolveProject(react({ features: entry.features }), adapters);
            return true;
          } catch {
            return false;
          }
        })(),
        `react + router + ${label}`,
      ).toBe(entry.reactOk);
    }
  });

  it('is indifferent to the styling system and the UI library', () => {
    for (const styling of ['tailwind', 'bootstrap'] as StylingId[]) {
      for (const uiLibrary of ['none', 'mui'] as UiLibraryId[]) {
        expect(() => resolveProject(react({ styling, uiLibrary }), adapters)).not.toThrow();
      }
    }
    expect(
      evaluateCombination([
        REACT_DECLARATION,
        VITE_DECLARATION,
        BOOTSTRAP_DECLARATION,
        MUI_DECLARATION,
        REACT_ROUTER_DECLARATION,
        CLIENT_ROUTE_FALLBACK_DECLARATION,
      ]).compatible,
    ).toBe(true);
  });
});

