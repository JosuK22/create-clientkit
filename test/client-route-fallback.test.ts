describe('the requirement is a capability, not React Router', () => {
  it('a hypothetical router that routes on the client satisfies it', () => {
    // The strongest available statement: the feature works with a router that
    // does not exist, has never been written, and that it cannot name.
    const hypothetical: AdapterDeclaration = {
      id: 'angular-router',
      kind: 'router',
      displayName: 'A router that is not React Router',
      provides: ['client-side-routing'],
      requires: [],
    };
    expect(evaluateCombination([hypothetical, CLIENT_ROUTE_FALLBACK_DECLARATION]).compatible).toBe(
      true,
    );
  });

  it('a hypothetical router with only spa-routing is refused, naming the capability', () => {
    const hypothetical: AdapterDeclaration = {
      id: 'angular-router',
      kind: 'router',
      displayName: 'A router that only avoids reloads',
      provides: ['spa-routing'],
      requires: [],
    };
    const report = evaluateCombination([hypothetical, CLIENT_ROUTE_FALLBACK_DECLARATION]);
    expect(report.compatible).toBe(false);
    expect(JSON.stringify(report)).toContain('client-side-routing');
  });

  it('file-based-routing does not satisfy it either, in either direction', () => {
    // Neither capability implies the other, and this is the assertion that
    // would fail if somebody made one of them provide the other for
    // convenience.
    const fileBased: AdapterDeclaration = {
      id: 'nextjs',
      kind: 'framework',
      displayName: 'routes by file',
      provides: ['file-based-routing'],
      requires: [],
    };
    expect(evaluateCombination([fileBased, CLIENT_ROUTE_FALLBACK_DECLARATION]).compatible).toBe(
      false,
    );

    const clientSide: AdapterDeclaration = {
      id: 'angular-router',
      kind: 'router',
      displayName: 'routes in the browser',
      provides: ['client-side-routing'],
      requires: [],
    };
    expect(evaluateCombination([clientSide, NOT_FOUND_DECLARATION]).compatible).toBe(false);
  });

  it('names no adapter anywhere in what it declares', () => {
    const declared = JSON.stringify(CLIENT_ROUTE_FALLBACK_DECLARATION);
    for (const name of ['react', 'vite', 'tailwind', 'bootstrap', 'mui', 'astro']) {
      expect(declared.toLowerCase(), `declaration mentions ${name}`).not.toContain(name);
    }
  });
});

