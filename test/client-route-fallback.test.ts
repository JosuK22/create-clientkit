describe('the generated view', () => {
  const view = () => fileAt('src/pages/NotFoundPage.tsx');

  it('has exactly one primary heading', () => {
    expect([...view().matchAll(/<h1[\s>]/g)]).toHaveLength(1);
  });

  it('renders inside the shared layout, so it gets the main landmark', () => {
    expect(view()).toContain('<BaseLayout>');
    expect(fileAt('src/layouts/BaseLayout.tsx')).toContain('<main id="main"');
  });

  it('offers a keyboard-reachable link back to the site root', () => {
    // A real anchor with a real href: reachable by tab, activated by Enter, and
    // working with JavaScript disabled. A div with an onClick would satisfy a
    // click-based test and none of that.
    expect(view()).toMatch(/<a href="\/"/);
    expect(view()).not.toContain('onClick');
    expect(view()).not.toContain('role="button"');
  });

  it('names no styling system, and uses only classes both stylesheets define', () => {
    const source = view();
    for (const name of ['tailwind', 'bootstrap', 'bg-', 'btn-primary', 'container-fluid']) {
      expect(source.toLowerCase(), `the view mentions ${name}`).not.toContain(name);
    }

    const tailwind = readFileSync(
      path.join(TEMPLATES_ROOT, 'styling', 'tailwind', 'styles.global.css'),
      'utf8',
    );
    const bootstrap = readFileSync(
      path.join(TEMPLATES_ROOT, 'styling', 'bootstrap', 'styles.global.css'),
      'utf8',
    );
    const used = [...source.matchAll(/className="([^"{]+)"/g)].flatMap((match) =>
      match[1]!.split(/\s+/).filter(Boolean),
    );
    expect(used.length).toBeGreaterThan(0);
    for (const className of used) {
      expect(tailwind, `tailwind defines no .${className}`).toContain(`.${className}`);
      expect(bootstrap, `bootstrap defines no .${className}`).toContain(`.${className}`);
    }
  });

  it('names no router package, so a different router would need no edit', () => {
    expect(view()).not.toContain('react-router');
    expect(view()).not.toContain('<Link');
  });

  it('is byte-identical whichever styling system or UI library is selected', () => {
    const variants = [
      view(),
      fileAt('src/pages/NotFoundPage.tsx', { styling: 'bootstrap' as StylingId }),
      fileAt('src/pages/NotFoundPage.tsx', { uiLibrary: 'mui' as UiLibraryId }),
    ];
    expect(new Set(variants).size).toBe(1);
  });
});

