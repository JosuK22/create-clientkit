describe('the contract is explicit about what it will not claim', () => {
  const contract = resolveClientRouteFallbackContract();

  it('guarantees a rendered view and an ordered catch-all', () => {
    expect(contract.catchAllPath).toBe('*');
    expect(contract.guarantees).toContain('renders-fallback-view');
    expect(contract.guarantees).toContain('catch-all-route');
    expect(contract.guarantees).toContain('catch-all-is-last');
  });

  it('puts the HTTP status out of scope, in the contract rather than only in prose', () => {
    // The single most important assertion in this file. A future edit that
    // decides the feature "is really a 404 after all" has to delete this.
    expect(contract.outOfScope).toContain('http-404-status');
    expect(contract.outOfScope).toContain('crawler-visible-not-found');
    expect(contract.outOfScope).toContain('server-rendered-not-found');
    expect(contract.outOfScope).toContain('host-configuration');
  });

  it('guarantees nothing about status codes, servers or crawlers', () => {
    for (const guarantee of CLIENT_ROUTE_FALLBACK_GUARANTEES) {
      expect(guarantee).not.toMatch(/404|status|http|server|crawler/i);
    }
  });

  it('never lists the same claim as both guaranteed and out of scope', () => {
    const guaranteed = new Set<string>(CLIENT_ROUTE_FALLBACK_GUARANTEES);
    for (const excluded of CLIENT_ROUTE_FALLBACK_OUT_OF_SCOPE) {
      expect(guaranteed.has(excluded), `${excluded} is on both lists`).toBe(false);
    }
  });

  it('is pure and serialises in a fixed order', () => {
    expect(serialiseClientRouteFallbackContract(resolveClientRouteFallbackContract())).toBe(
      serialiseClientRouteFallbackContract(resolveClientRouteFallbackContract()),
    );
    expect(serialiseClientRouteFallbackContract(contract).indexOf('catchAllPath')).toBeLessThan(
      serialiseClientRouteFallbackContract(contract).indexOf('outOfScope'),
    );
  });
});

