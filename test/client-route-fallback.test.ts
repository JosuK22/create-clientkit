/**
 * The client-side route fallback, and the distinction it exists to protect.
 *
 * Every other feature suite is mostly about what the feature does. This one is
 * mostly about what it is *not*, because the whole reason it is a separate
 * adapter rather than a relaxation of Stage 8 is a difference that is easy to
 * argue away and expensive to get wrong:
 *
 *     not-found            != client-route-fallback
 *     file-based-routing   != client-side-routing
 *
 * The first pair is a property of the response against a property of the
 * render. The second is what decides which projects may claim which. So the
 * sharpest tests here are the refusals - and the ones asserting that no
 * generated byte anywhere claims an HTTP 404.
 */

