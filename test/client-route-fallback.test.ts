describe('the rest of the project is untouched', () => {
  it('every file except the router and the view is what it was without the feature', () => {
    const withFeature = new Map(
      planFor().plan.operations.flatMap((operation) =>
        operation.type === 'write' ? [[operation.path, operation.content] as const] : [],
      ),
    );
    const without = new Map(
      planFor({ features: ['starter:full'] }).plan.operations.flatMap((operation) =>
        operation.type === 'write' ? [[operation.path, operation.content] as const] : [],
      ),
    );

    const added: string[] = [];
    for (const [file, content] of withFeature) {
      if (!without.has(file)) {
        added.push(file);
        continue;
      }
      if (file === 'src/routes/AppRouter.tsx') continue;
      // Since Stage 14 the provenance file records which features were
      // selected, so it differs by exactly the name of this one. That is the
      // file's job; before then it reported every project as having none.
      if (file === '.client-site.json') {
        expect(content).toContain('client-route-fallback');
        expect(without.get(file)).not.toContain('client-route-fallback');
        continue;
      }
      expect(content, `${file} changed`).toBe(without.get(file));
    }
    expect(added).toEqual(['src/pages/NotFoundPage.tsx']);
  });

  it('Astro generates exactly what it did before', () => {
    const plan = (features: readonly FeatureId[]) =>
      renderPlan(
        planManifest(astro(features), {
          registry: v1Registry,
          cliVersion: '9.9.9',
          generatedAt: '2026-01-01T00:00:00.000Z',
          mode: 'full',
          templateId: 'astro-tailwind',
        }).plan,
        TEMPLATES_ROOT,
      );
    expect(plan(['starter:full'])).toBe(plan(['starter:full']));
  });

  it('the same manifest produces the same plan twice', () => {
    expect(renderPlan(planFor().plan, TEMPLATES_ROOT)).toBe(
      renderPlan(planFor().plan, TEMPLATES_ROOT),
    );
  });

  it('no generated content carries a machine value or an unresolved token', () => {
    for (const operation of planFor({ uiLibrary: 'mui' as UiLibraryId }).plan.operations) {
      if (operation.type !== 'write') continue;
      expect(operation.content).not.toContain(TEST_CWD);
      expect(operation.content).not.toContain('\r\n');
      expect(operation.content).not.toMatch(/\{\{\s*[a-zA-Z]/);
    }
  });
});

