describe('nothing generated claims an HTTP 404', () => {
  const generated = (over: Partial<ProjectManifest> = {}): readonly [string, string][] =>
    planFor(over).plan.operations.flatMap((operation) =>
      operation.type === 'write' ? [[operation.path, operation.content] as const] : [],
    );

  it('no generated file claims to send, set or return a 404 status', () => {
    for (const [file, content] of generated()) {
      expect(content, `${file} claims to produce a status`).not.toMatch(
        /(?:status|statusCode|res\.status|sendStatus|response)\s*[:=(]\s*['"`]?404/i,
      );
    }
  });

  it('the view says plainly that the response is not a 404', () => {
    const view = fileAt('src/pages/NotFoundPage.tsx');
    expect(view).toContain('200');
    expect(view).toMatch(/soft 404/);
    expect(view).toMatch(/not a response|component, not a response/);
  });

  it('the router says the same thing, so the caveat survives deleting either file', () => {
    const source = fileAt('src/routes/AppRouter.tsx');
    expect(source).toMatch(/usually a 200/);
    expect(source).toMatch(/not a 404/);
  });

  it('the caveat is present whether or not the feature is selected', () => {
    // Without the feature the router explains what a catch-all would and would
    // not buy; with it, the same caveat about the same catch-all. A reader must
    // not have to select the feature to learn the limitation.
    for (const features of [['starter:full'], ['starter:full', 'client-route-fallback']]) {
      const source = fileAt('src/routes/AppRouter.tsx', { features: features as FeatureId[] });
      expect(source, features.join('+')).toMatch(/not a 404/);
    }
  });

  it('the view fabricates no metadata, ARIA label or alt text', () => {
    // The generator has no truthful source for what a page nobody asked for
    // should say about itself, so it says nothing about it.
    const view = withoutComments(fileAt('src/pages/NotFoundPage.tsx'));
    expect(view).not.toContain('useDocumentMeta');
    expect(view).not.toContain('aria-label');
    expect(view).not.toContain('alt=');
    expect(view).not.toContain('<meta');
    expect(view).not.toContain('canonical');
    expect(view).not.toContain('robots');
  });
});

