describe('the route table composes rather than being edited', () => {
  const router = () => fileAt('src/routes/AppRouter.tsx');

  it('holds both routes, with the catch-all after the home route', () => {
    const source = router();
    expect(source).toContain('<Route path="/" element={children} />');
    expect(source).toContain('<Route path="*" element={<NotFoundPage />} />');
    expect(source.indexOf('path="/"')).toBeLessThan(source.indexOf('path="*"'));
  });

  it('imports the view by the path the architecture resolved', () => {
    expect(router()).toContain("import { NotFoundPage } from '../pages/NotFoundPage';");
  });

  it('records both owners, so neither adapter edited the other', () => {
    const operation = planFor().plan.operations.find(
      (entry) => entry.path === 'src/routes/AppRouter.tsx',
    );
    expect(operation?.origin).toContain('router:react-router');
    expect(operation?.origin).toContain('feature:client-route-fallback');
  });

  it('emits no catch-all when the feature is not selected', () => {
    // Matched against the JSX rather than the whole file: the routerless
    // version documents what a catch-all would buy, and that prose quotes
    // `path="*"` while emitting no such route.
    const source = fileAt('src/routes/AppRouter.tsx', { features: ['starter:full'] });
    expect(source).not.toContain('<Route path="*"');
    expect(source).not.toContain('NotFoundPage');
  });

  it('sorts the catch-all last however the contributions arrive', () => {
    // Order is declared, not incidental. Reversing the contribution list must
    // not reverse the table - if it did, a catch-all could end up above the
    // home route and swallow it.
    const config = contributionsOf().flatMap((contribution) => contribution.config);
    const forwards = collectRoutes(config, 'app.router', 'routes');
    const backwards = collectRoutes([...config].reverse(), 'app.router', 'routes');
    expect(forwards.map((claim) => claim.entry.path)).toEqual(['/', '*']);
    expect(backwards.map((claim) => claim.entry.path)).toEqual(['/', '*']);
  });

  it('would place a lower-ordered catch-all first, which is why the order is high', () => {
    // Proves the ordering is doing work rather than coinciding with insertion.
    const config = contributionsOf().flatMap((contribution) => contribution.config);
    const sabotaged = config.map((contribution) =>
      contribution.at === 'routes' && (contribution.value as { path?: string }).path === '*'
        ? { ...contribution, value: { ...(contribution.value as object), order: -1 } }
        : contribution,
    );
    expect(
      collectRoutes(sabotaged, 'app.router', 'routes').map((claim) => claim.entry.path),
    ).toEqual(['*', '/']);
    expect(CATCH_ALL_ORDER).toBeGreaterThan(0);
  });

  it('leaves every other wrapper outside the router, so it covers both routes', () => {
    /*
     * The defect this stage found, and the reason the router's order changed.
     *
     * The page a router wrapper is handed becomes one route's element. So a
     * wrapper nested *inside* the router wraps that route alone, and every
     * other route renders outside it. With MUI selected, the fallback rendered
     * with no theme, no baseline and no styling engine while the home page had
     * all three - and nothing failed, which is what made it worth a test.
     *
     * Asserted structurally rather than by naming MUI: any wrapper, present or
     * future, has to close after the router closes.
     */
    const root = fileAt('src/App.tsx', { uiLibrary: 'mui' as UiLibraryId });
    const open = [...root.matchAll(/<([A-Z][A-Za-z]*)>/g)].map((match) => match[1]!);
    expect(open).toContain('AppRouter');
    expect(open.at(-1)).toBe('AppRouter');
    expect(open.indexOf('AppProviders')).toBeLessThan(open.indexOf('AppRouter'));
  });

  it('refuses a second adapter claiming the same catch-all differently', () => {
    const config = contributionsOf().flatMap((contribution) => contribution.config);
    const rival: Contribution = {
      ...emptyContribution('feature:rival'),
      config: [
        {
          target: 'app.router',
          at: 'routes',
          value: {
            path: '*',
            element: { kind: 'component', importName: 'Other', role: 'page.notFound' },
            order: CATCH_ALL_ORDER,
          },
          owner: 'feature:rival',
          reason: 'a second view for the same address',
        },
      ],
    };
    expect(() => collectRoutes([...config, ...rival.config], 'app.router', 'routes')).toThrow(
      /both want to render "\*"/,
    );
  });

  it('refuses a route whose component role the architecture does not map', () => {
    const { project } = resolveWithAdapters(react(), TEMPLATES_ROOT);
    const homeless: Contribution = {
      ...emptyContribution('feature:nowhere'),
      config: [
        {
          target: 'app.router',
          at: 'routes',
          value: {
            path: '/nowhere',
            element: { kind: 'component', importName: 'Nowhere', role: 'config.framework' },
            order: 5,
          },
          owner: 'feature:nowhere',
          reason: 'a route the architecture cannot place',
        },
      ],
    };
    expect(() => composedRouter(project, [...contributionsOf(), homeless])).toThrow(
      /maps no "config\.framework" role/,
    );
  });
});

