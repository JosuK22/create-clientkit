const fileAt = (target: string, over: Partial<ProjectManifest> = {}): string => {
  const operation = planFor(over).plan.operations.find((entry) => entry.path === target);
  return operation?.type === 'write' ? operation.content : '';
};

const contributionsOf = (over: Partial<ProjectManifest> = {}): readonly Contribution[] =>
  resolveWithAdapters(react(over), TEMPLATES_ROOT).contributions;

const fallbackContribution = (over: Partial<ProjectManifest> = {}): Contribution => {
  const found = contributionsOf(over).find(
    (contribution) => contribution.owner === 'feature:client-route-fallback',
  );
  if (found === undefined) throw new Error('the feature contributed nothing at all');
  return found;
};

/**
 * Source with its comments removed.
 *
 * Needed because the honest thing and the forbidden thing are spelled the same
 * way here: the generated view explains why it does *not* set a document title,
 * which means naming the hook it declines to call. An assertion about what the
 * component does has to read the code rather than the prose about the code.
 */
const withoutComments = (source: string): string =>
  source
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');

const requiredCapabilities = (declaration: AdapterDeclaration): readonly string[] =>
  declaration.requires.flatMap((entry) =>
    entry.kind === 'requires'
      ? [entry.capability]
      : entry.kind === 'requiresOneOf'
        ? [...entry.capabilities]
        : [],
  );

const refusalText = (manifest: ProjectManifest): string => {
  let error: CliError | undefined;
  try {
    resolveProject(manifest, adapters);
  } catch (thrown) {
    error = thrown as CliError;
  }
  expect(error, 'the combination was accepted').toBeInstanceOf(CliError);
  return `${error?.message ?? ''}\n${error?.hint ?? ''}`;
};

