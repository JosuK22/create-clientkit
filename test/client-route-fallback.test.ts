describe('the adapter stays inside the contract', () => {
  const source = readFileSync(
    path.resolve(import.meta.dirname, '..', 'src', 'adapters', 'client-route-fallback.ts'),
    'utf8',
  );

  it('touches no filesystem, process, shell or network API', () => {
    for (const forbidden of [
      'node:fs',
      'node:child_process',
      'node:process',
      'readFileSync',
      'writeFileSync',
      'execSync',
      'spawn',
      'fetch(',
    ]) {
      expect(source, `the adapter uses ${forbidden}`).not.toContain(forbidden);
    }
  });

  it('imports no other adapter', () => {
    const imports = [...source.matchAll(/^import[^;]*from '([^']+)';/gm)].map((match) => match[1]);
    for (const specifier of imports) {
      expect(specifier, `the adapter imports ${specifier}`).not.toMatch(
        /\.\/(react|react-router|vite|tailwind|bootstrap|astro|mui|not-found)\.js$/,
      );
    }
  });

  it('contains no concrete output path', () => {
    // Comments stripped first: the header explains what the adapter refuses to
    // learn, and it cannot do that without naming the path once.
    const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
    expect(code).not.toContain('src/pages');
    expect(code).not.toContain('src/routes');
    // Its own template's filename is fair game - that file is the adapter's,
    // shipped in the adapter's own directory. Where it *lands* is not.
    expect(code).toContain("'client-route-fallback'");
  });

  it('is a pure function of its inputs', () => {
    expect(JSON.stringify(fallbackContribution())).toBe(JSON.stringify(fallbackContribution()));
  });

  it('resolves identically whatever the rest of the manifest says', () => {
    const feature = adapters.feature('client-route-fallback');
    expect(feature.resolve(react())).toEqual(
      feature.resolve(react({ styling: 'bootstrap', uiLibrary: 'mui', language: 'ts' })),
    );
  });
});

