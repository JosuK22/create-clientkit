describe('the fallback is a feature, and a different one from not-found', () => {
  it('occupies the feature dimension', () => {
    expect(CLIENT_ROUTE_FALLBACK_DECLARATION.kind).toBe('feature');
    expect(CLIENT_ROUTE_FALLBACK_DECLARATION.id).toBe('client-route-fallback');
  });

  it('is addressable only as a feature', () => {
    expect(adapters.feature('client-route-fallback').declaration.id).toBe('client-route-fallback');
    expect(() => adapters.router('client-route-fallback' as never)).toThrow(CliError);
    expect(() => adapters.styling('client-route-fallback' as never)).toThrow(CliError);
    expect(() => adapters.uiLibrary('client-route-fallback' as never)).toThrow(CliError);
  });

  it('is one of the implemented features, beside not-found rather than instead of it', () => {
    expect(adapters.implementedFeatures()).toContain('client-route-fallback');
    expect(adapters.implementedFeatures()).toContain('not-found');
    expect(adapters.hasFeature('client-route-fallback')).toBe(true);
  });

  it('is a distinct id, declaration and requirement from not-found', () => {
    expect(CLIENT_ROUTE_FALLBACK_DECLARATION.id).not.toBe(NOT_FOUND_DECLARATION.id);
    expect(CLIENT_ROUTE_FALLBACK_DECLARATION.displayName).not.toBe(
      NOT_FOUND_DECLARATION.displayName,
    );
    expect(requiredCapabilities(CLIENT_ROUTE_FALLBACK_DECLARATION)).toEqual([
      'client-side-routing',
    ]);
    expect(requiredCapabilities(NOT_FOUND_DECLARATION)).toEqual(['file-based-routing']);
  });

  it('provides nothing, because nothing can meaningfully require it', () => {
    expect(CLIENT_ROUTE_FALLBACK_DECLARATION.provides).toEqual([]);
  });

  it('requires no styling system, UI library, build tool or language', () => {
    expect(requiredCapabilities(CLIENT_ROUTE_FALLBACK_DECLARATION)).not.toContain('vite-plugins');
    expect(requiredCapabilities(CLIENT_ROUTE_FALLBACK_DECLARATION)).not.toContain('typescript');
    expect(requiredCapabilities(CLIENT_ROUTE_FALLBACK_DECLARATION)).not.toContain(
      'composed-stylesheet',
    );
    expect(requiredCapabilities(CLIENT_ROUTE_FALLBACK_DECLARATION)).not.toContain('react-runtime');
  });
});

